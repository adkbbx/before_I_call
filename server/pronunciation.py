# Apply longer phrases first, and replace only the original input once.
NUMERALS = r'\d零〇一二三四五六七八九十百千万億兆'
PATTERN = re.compile('|'.join(
    (rf'(?<![{NUMERALS}])' if re.match(rf'[{NUMERALS}]', word) else '') + re.escape(word)
    for word in sorted(READINGS, key=len, reverse=True)
))


def speech_text(text: str, language: str = 'ja') -> str:
    return PATTERN.sub(lambda match: READINGS[match.group()], text) if language == 'ja' else text


def dictionary_rules():
    # ElevenLabs takes the first matching rule, so compounds must precede parts.
    return [{'type': 'alias', 'string_to_replace': word, 'alias': READINGS[word]} for word in sorted(READINGS, key=len, reverse=True)]
